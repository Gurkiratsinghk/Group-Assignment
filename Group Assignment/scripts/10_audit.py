recompute_rows = []


def add_recompute(label, original, recomputed):
    diff = abs(original - recomputed)
    recompute_rows.append({"quantity": label, "original": original, "recomputed": recomputed, "abs_diff": diff})


print("\n[2a] Step 1 (sample mean/s/SE) via statsmodels.stats.weightstats.DescrStatsW (originally: pandas/numpy)...")
sample1 = pd.read_csv("data/processed/sample_n40.csv")["range_pct"].to_numpy(dtype=float)
d1 = DescrStatsW(sample1, ddof=1)
orig_mean1 = float(pd.Series(sample1).mean())
orig_std1 = float(pd.Series(sample1).std(ddof=1))
orig_se1 = orig_std1 / np.sqrt(len(sample1))
add_recompute("Step1 sample_mean", orig_mean1, d1.mean)
add_recompute("Step1 sample_std", orig_std1, d1.std)
add_recompute("Step1 SE", orig_se1, d1.std_mean)

print("\n[2b] Step 2 (95% CI bounds) via DescrStatsW.tconfint_mean (originally: scipy.stats.t.ppf manual)...")
ci_lo, ci_hi = d1.tconfint_mean(alpha=ALPHA)
orig_t_crit = float(stats.t.ppf(1 - ALPHA / 2, df=len(sample1) - 1))
orig_ci_lo = orig_mean1 - orig_t_crit * orig_se1
orig_ci_hi = orig_mean1 + orig_t_crit * orig_se1
add_recompute("Step2 CI lower", orig_ci_lo, ci_lo)
add_recompute("Step2 CI upper", orig_ci_hi, ci_hi)

print("\n[2c] Step 5 (t, p) via statsmodels OLS regression of (x - mu0) on a constant (originally: scipy.stats.ttest_1samp)...")
sample_a = pd.read_csv("data/processed/sample_it_n40.csv")["range_pct"].to_numpy(dtype=float)
y = sample_a - 2.0
X = np.ones_like(y)
ols_model = sm.OLS(y, X).fit()
t_ols = float(ols_model.tvalues[0])
p_ols_two_sided = float(ols_model.pvalues[0])
p_ols_one_tailed = p_ols_two_sided / 2 if t_ols > 0 else 1 - p_ols_two_sided / 2
orig_t_a, orig_p_a = stats.ttest_1samp(sample_a, popmean=2.0, alternative="greater")
add_recompute("Step5 t_statistic", float(orig_t_a), t_ols)
add_recompute("Step5 p_value", float(orig_p_a), p_ols_one_tailed)

print("\n[2d] Step 6 Test A (same as Step 5) -- OLS recompute confirms the value above.")

print("\n[2e] Step 6 Test B via statsmodels CompareMeans (originally: scipy.stats.ttest_ind)...")
xb1 = pd.read_csv("data/processed/sample_testB_it_n40.csv")["range_pct"].to_numpy(dtype=float)
xb2 = pd.read_csv("data/processed/sample_testB_fmcg_n40.csv")["range_pct"].to_numpy(dtype=float)
cm = CompareMeans(DescrStatsW(xb1, ddof=1), DescrStatsW(xb2, ddof=1))
t_pooled_cm, p_pooled_cm, dof_pooled_cm = cm.ttest_ind(usevar="pooled")
orig_t_b, orig_p_b = stats.ttest_ind(xb1, xb2, equal_var=True)
add_recompute("Step6-B t_statistic (pooled, current fixed sample)", float(orig_t_b), t_pooled_cm)
add_recompute("Step6-B p_value (pooled, current fixed sample)", float(orig_p_b), p_pooled_cm)

print("\n[2f] Step 6 Test C via DescrStatsW.ttest_mean on the difference column (originally: scipy.stats.ttest_rel)...")
sample_c = pd.read_csv("data/processed/sample_testC_paired_n40.csv")
diff_c = (sample_c["abs_overnight_gap_pct"] - sample_c["abs_intraday_move_pct"]).to_numpy(dtype=float)
d_diff = DescrStatsW(diff_c, ddof=1)
t_diff, p_diff, dof_diff = d_diff.ttest_mean(value=0)
orig_t_c, orig_p_c = stats.ttest_rel(sample_c["abs_overnight_gap_pct"], sample_c["abs_intraday_move_pct"])
add_recompute("Step6-C t_statistic", float(orig_t_c), float(t_diff))
add_recompute("Step6-C p_value", float(orig_p_c), float(p_diff))

